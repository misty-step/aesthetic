export const sha256 = (...parts) => {
  const hash = createHash('sha256');
  for (const part of parts) hash.update(part);
  return hash.digest('hex');
};

/** A token by path ('components.code.backgroundColor'), following {references}. */
export function token(tokens, path) {
  const value = path.split('.').reduce((node, key) => node?.[key], tokens);
  if (value === undefined) throw new Error(`tokens.json has no ${path}`);
  const ref = typeof value === 'string' && /^\{([\w.-]+)\}$/.exec(value);
  return ref ? token(tokens, ref[1]) : value;
}

function checkTokens(tokens) {
  const problems = [];
  for (const [name, expected] of Object.entries(COMPONENTS)) {
    for (const [field, want] of Object.entries(expected)) {
      const have = tokens.components?.[name]?.[field];
      const same = want.startsWith('{') ? have === want : have === token(tokens, want);
      if (!same) problems.push(`components.${name}.${field} is ${JSON.stringify(have)}; spine.css expects ${want.startsWith('{') ? want : token(tokens, want)}`);
    }
  }
  for (const [role, style] of Object.entries(tokens.typography)) {
    if (!FONTS.some(font => font.family === style.fontFamily)) problems.push(`typography.${role} names ${style.fontFamily}, which has no file in FONTS`);
  }
  return problems;
}

/** Each face's bytes and licence, refused unless they match the upstream pins. */
async function loadFonts() {
  return Promise.all(FONTS.map(async font => {
    const bytes = await readFile(join(SRC, 'fonts', font.file));
    const licenceBytes = await readFile(join(SRC, 'fonts', font.licence));
    if (sha256(bytes) !== font.sha256) throw new Error(`src/fonts/${font.file} differs from its upstream file (${font.source})`);
    if (sha256(licenceBytes) !== font.licenceSha256) throw new Error(`src/fonts/${font.licence} differs from its upstream licence (${font.licenceSource})`);
    const face = create(bytes);
    const wght = face.variationAxes?.wght;
    return { ...font, bytes, licenceBytes, face, weight: wght ? `${wght.min} ${wght.max}` : String(face['OS/2'].usWeightClass) };
  }));
}

async function evaluate(contents) {
  const result = await build({
    stdin: { contents, resolveDir: ROOT, sourcefile: 'identity-collect.ts', loader: 'ts' },
    bundle: true, write: false, platform: 'node', format: 'esm', target: 'node20', logLevel: 'silent',
  });
  return import('data:text/javascript;base64,' + Buffer.from(result.outputFiles[0].contents).toString('base64'));
}

async function bundle(entry, { minify = true, legalComments = 'none' } = {}) {
  const result = await build({
    entryPoints: [join(SRC, entry)], bundle: true, write: false, platform: 'browser', format: 'esm', target: 'es2022',
    minify, legalComments, charset: 'utf8', absWorkingDir: ROOT, banner: { js: `/* ${HEADER} */` }, logLevel: 'silent',
  });
  return result.outputFiles[0].text;
}

const decl = entries => entries.map(([name, value]) => `--${name}:${value}`).join(';');

/** The custom properties brand.css declares, by scope: html[data-brand], then each theme. */
function properties(tokens, fonts) {
  const stack = family => {
    const font = fonts.find(f => f.family === family);
    return `${JSON.stringify(family)}, ${font.generic}`;
  };
  const fixed = Object.entries(tokens.colors).map(([name, value]) => [`color-${name}`, value]);
  for (const [role, style] of Object.entries(tokens.typography)) {
    fixed.push(
      [`font-${role}`, stack(style.fontFamily)],
      [`${role}-size`, style.fontSize],
      [`${role}-weight`, style.fontWeight],
      [`${role}-leading`, style.lineHeight],
      [`${role}-tracking`, style.letterSpacing ?? 'normal'],
      [`type-${role}`, `${style.fontWeight} ${style.fontSize}/${style.lineHeight} ${stack(style.fontFamily)}`],
    );
  }
  for (const [name, path] of Object.entries(RADII)) fixed.push([`radius-${name}`, token(tokens, path)]);
  for (const [name, value] of Object.entries(tokens.spacing)) fixed.push([`space-${name}`, value]);
  for (const [name, path] of Object.entries(PADDING)) fixed.push([`${name}-padding`, token(tokens, path)]);
  for (const [name, path] of Object.entries(FIXED)) fixed.push([name, token(tokens, path)]);
  const theme = i => Object.entries(THEME).map(([name, paths]) => [name, token(tokens, paths[i])]);
  return { fixed, light: theme(0), dark: theme(1) };
}

const NAMED = /\b(?:white|black|red|green|blue|gray|grey|silver|purple|navy|yellow|orange|pink|indigo|violet)\b/i;
const COLOUR = /#[0-9a-f]{3,8}\b|\b(?:rgba?|hsla?|hwb|lab|lch|oklab|oklch|color)\(/i;
/**
 * The hand-written stylesheets may only spend tokens: no colour literal, no family name, no type shorthand of their own,
 * every var() declared by brand.css or by the sheet itself, and the brand scope as attrs.ts writes it.
 */
function lint(file, css, known, scope) {
  const problems = [];
  const text = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const own = new Set([...text.matchAll(/(--[\w-]+)\s*:/g)].map(m => m[1].slice(2)));
  for (const [, block] of text.matchAll(/\{([^{}]*)\}/g)) {
    for (const declaration of block.split(';')) {
      const at = declaration.indexOf(':');
      if (at < 0) continue;
      const property = declaration.slice(0, at).trim(), value = declaration.slice(at + 1).trim();
      if (COLOUR.test(value) || NAMED.test(value)) problems.push(`${file}: ${property}: ${value} is a colour literal; use a token`);
      if (property === 'font-family' && !/^(?:var\(--font-[\w-]+\)|inherit)$/.test(value)) problems.push(`${file}: font-family: ${value}; use var(--font-<role>)`);
      if (property === 'font' && !/^(?:var\(--type-[\w-]+\)|inherit)$/.test(value)) problems.push(`${file}: font: ${value}; use var(--type-<role>)`);
    }
  }
  for (const [, name] of text.matchAll(/var\(--([\w-]+)/g)) {
    if (!known.has(name) && !own.has(name)) problems.push(`${file}: var(--${name}) is not a brand.css token`);
  }
  for (const [attribute] of text.matchAll(/\[data-brand[^\]]*\]/g)) {
    if (attribute !== scope) problems.push(`${file}: ${attribute} does not match attrs.ts (${scope})`);
  }
  return problems;
}

/** The lockup rules: the mark LOCKUP_MARK times the display face's capital height, centred on the capitals, then the name. */
function lockupCss(display) {
  const face = display.face;
  const caps = face.capHeight / face.unitsPerEm;
  // With line-height 1, flex centring puts the mark's middle at (ascent - descent) / 2 above the baseline;
  // the capitals' middle sits at caps / 2. Any difference moves the mark onto the capitals.
  const shift = Math.round(((face.ascent + face.descent) / face.unitsPerEm / 2 - caps / 2) * 1000) / 1000;
  return [
    `.ms-lockup{display:inline-flex;align-items:center;gap:${LOCKUP_GAP}em;color:inherit;font-family:var(--font-display);font-size:var(--title-size);font-weight:var(--display-weight);letter-spacing:var(--display-tracking);line-height:1;text-decoration:none;white-space:nowrap}`,
    `.ms-lockup>.ms-mark{display:block;flex:none;width:auto;height:${Math.round(caps * LOCKUP_MARK * 1000) / 1000}em${shift ? `;translate:0 ${shift}em` : ''}}`,
  ].join('\n');
}

