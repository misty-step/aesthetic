function markModule(marks, favicon) {
  const s = JSON.stringify;
  return `// ${HEADER}
/** The step mark in colour: the leading parallelogram Indigo, the trailing one Violet. Decorative (aria-hidden); size it with CSS. */
export const MARK_SVG = ${s(marks.color)};
/** The step mark in currentColor, for Ink or white. Decorative (aria-hidden); size it with CSS. */
export const MONO_MARK_SVG = ${s(marks.mono)};
/** The favicon drawing: the colour mark centred in a square (identity/icons/favicon.svg). */
export const FAVICON_SVG = ${s(favicon)};

const NAMES = ${s(NAMES)};
const quote = JSON.stringify;
const esc = value => String(value).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

/** The lockup brand.css styles: .ms-lockup holding the mark (svg.ms-mark) and the name (.ms-name). With opts.href it is the link. */
export function lockup(name, opts = {}) {
  if (!NAMES.includes(name)) throw new Error(\`lockup: unknown name \${quote(name)}; expected \${NAMES.map(n => quote(n)).join(' or ')}\`);
  const variant = opts.variant ?? 'color';
  if (variant !== 'color' && variant !== 'mono') throw new Error(\`lockup: unknown variant \${quote(variant)}; expected "color" or "mono"\`);
  const inner = \`\${variant === 'mono' ? MONO_MARK_SVG : MARK_SVG}<span class="ms-name">\${esc(name)}</span>\`;
  if (opts.href === undefined) return \`<span class="ms-lockup">\${inner}</span>\`;
  return \`<a class="ms-lockup" href="\${esc(opts.href)}"\${opts.label === undefined ? '' : \` aria-label="\${esc(opts.label)}"\`}>\${inner}</a>\`;
}
`;
}

function markTypes() {
  return `// ${HEADER}
/** The step mark in colour: the leading parallelogram Indigo, the trailing one Violet. Decorative (aria-hidden); size it with CSS. */
export declare const MARK_SVG: string;
/** The step mark in currentColor, for Ink or white. Decorative (aria-hidden); size it with CSS. */
export declare const MONO_MARK_SVG: string;
/** The favicon drawing: the colour mark centred in a square (identity/icons/favicon.svg). */
export declare const FAVICON_SVG: string;
export type BrandName = ${NAMES.map(name => `'${name}'`).join(' | ')};
export interface LockupOptions {
  /** Return the lockup as <a class="ms-lockup" href>. */
  href?: string;
  /** The link's accessible name, when it should say more than the name it shows. */
  label?: string;
  /** 'color' (default): Indigo and Violet. 'mono': the mark in currentColor, like the name. */
  variant?: 'color' | 'mono';
}
export declare function lockup(name: BrandName, opts?: LockupOptions): string;
`;
}

function spineTypes({ icons, statuses }) {
  const union = names => names.map(name => `'${name}'`).join(' | ');
  return `// ${HEADER}
/** A glyph icon() draws: Lucide icons (ISC), several derived from Feather (MIT). The licences ship in spine.js. */
export type IconName = ${union(icons)};
/** A status. Its glyph takes sp-ok, sp-warn or sp-err; the words beside it stay ink. */
export type Status = ${union(statuses)};
/** The glyph as an SVG string: class "sp-icon" plus cls, drawn in currentColor, aria-hidden. Safe to call on the server. */
export declare function icon(name: IconName, cls?: string): string;
/** The status glyph (circle-check, triangle-alert or circle-x) with its status class: sp-ok, sp-warn or sp-err. */
export declare function statusIcon(status: Status): string;
/**
 * Installs the components' behaviour once, as listeners on the document, so markup rendered later works too:
 * [data-sp-dialog] opens a dialog and [data-sp-close] closes it; a .sp-pop menu opens beside its [popovertarget] and
 * takes the arrow keys; every [role="tab"] answers clicks, ArrowLeft, ArrowRight, Home and End; a .sp-setting row
 * folds its chooser open and shut; a toast's close button dismisses it. Calling it again does nothing.
 */
export declare function wire(): void;
/** Opens the dialog as a modal. However it closes, focus returns to the invoker, or to the button of the menu the invoker sat in. */
export declare function openDialog(dialog: HTMLDialogElement, invoker: HTMLElement): void;
/** Appends a toast (role="status") to the tray and returns it. It stays until dismissed; a fifth pushes the oldest out. */
export declare function toast(tray: HTMLElement, message: string, status?: Status): HTMLElement;
/** Writes the message into the input's #<id>-error note and marks the input invalid; null clears both. Throws when the note is missing. */
export declare function setInvalid(input: HTMLInputElement, message: string | null): void;
`;
}

export const rasterise = svg => new Resvg(svg, { fitTo: { mode: 'original' }, font: { loadSystemFonts: false } }).render().asPng();

/**
 * Everything generate.mjs owns under identity/: files (path -> exact contents), rasters (path -> the SVG source
 * resvg renders, checked by source hash because rasterisers differ in the last bit across platforms) and problems
 * (token and stylesheet rule breaks, which fail both modes).
 */
export async function outputs() {
  const tokenBytes = await readFile(AUTHORITY);
  const tokens = JSON.parse(tokenBytes);
  const problems = checkTokens(tokens);
  const fonts = await loadFonts();
  const files = new Map([['tokens.json', tokenBytes]]);
  for (const font of fonts) {
    files.set(`fonts/${font.file}`, font.bytes);
    files.set(`fonts/${font.licence}`, font.licenceBytes);
  }

  const attrsJs = await bundle('attrs.ts', { minify: false });
  const attrs = await evaluate(`export * from './src/attrs.ts';`);
  const scope = `[${Object.entries(attrs.HTML_ATTRS).map(([name, value]) => `${name}="${value}"`).join('][')}]`;
  const root = `html${scope}`;
  const props = properties(tokens, fonts);
  const known = new Set([...props.fixed, ...props.light].map(([name]) => name));
  const baseCss = await readFile(join(SRC, 'brand.css'), 'utf8');
  const spineCss = await readFile(join(SRC, 'spine.css'), 'utf8');
  problems.push(...lint('src/brand.css', baseCss, known, scope), ...lint('src/spine.css', spineCss, known, scope));

  const display = fonts.find(font => font.family === tokens.typography.display.fontFamily);
  files.set('brand.css', [
    `/* ${HEADER} Fonts: SIL Open Font License 1.1 (${fonts.map(font => font.family).join(', ')}); the licences sit in ./fonts. */`,
    ...fonts.map(font => `@font-face{font-family:${JSON.stringify(font.family)};src:url(./fonts/${font.file}) format("woff2");font-weight:${font.weight};font-style:normal;font-display:swap}`),
    `${root}{${decl(props.fixed)};${decl(props.light)};color-scheme:light}`,
    `${root}[data-theme="dark"]{${decl(props.dark)};color-scheme:dark}`,
    `@media (prefers-color-scheme:dark){${root}:not([data-theme]){${decl(props.dark)};color-scheme:dark}}`,
    baseCss.trim(),
    '/* The lockup: scripts/identity/mark.mjs and the display face\'s capital height. */',
    lockupCss(display),
  ].join('\n') + '\n');
  files.set('spine.css', `/* ${HEADER} Load it after brand.css, whose tokens it spends. */\n${spineCss.trim()}\n`);

  files.set('attrs.js', attrsJs);
  files.set('attrs.d.ts', attrsTypes(attrs));
  files.set('runtime.js', await bundle('runtime.ts'));
  files.set('runtime.d.ts', runtimeTypes());
  files.set('spine.js', await bundle('spine.ts', { legalComments: 'eof' }));
  const icons = await evaluate(`export { ICON_NAMES, STATUS_ICON } from './src/icons.ts';`);
  files.set('spine.d.ts', spineTypes({ icons: icons.ICON_NAMES, statuses: Object.keys(icons.STATUS_ICON) }));

  const c = tokens.colors;
  const colour = [c.primary, c.secondary];
  const white = token(tokens, FIXED['on-primary']);
  const favicon = faviconSvg(colour);
  const decorative = ' class="ms-mark" aria-hidden="true"';
  files.set('mark.js', markModule({ color: markSvg(colour, decorative), mono: markSvg('currentColor', decorative) }, favicon));
  files.set('mark.d.ts', markTypes());
  files.set('marks/mark.svg', markSvg(colour) + '\n');
  files.set('marks/mark-ink.svg', markSvg(c.ink) + '\n');
  files.set('marks/mark-white.svg', markSvg(white) + '\n');
  files.set('icons/favicon.svg', favicon + '\n');

  const sources = [
    ['icons/favicon-16.png', squareIcon(16, { fill: colour })],
    ['icons/favicon-32.png', squareIcon(32, { fill: colour })],
  ];
  for (const size of [180, 1024]) {
    sources.push(
      [`icons/app-${size}-ink.png`, squareIcon(size, { ground: c.ink, fill: colour, clear: true })],
      [`icons/app-${size}-indigo.png`, squareIcon(size, { ground: c.primary, fill: white, clear: true })],
      [`icons/app-${size}-black.png`, squareIcon(size, { ground: c.surface, fill: c.ink, clear: true })],
      [`icons/app-${size}-white.png`, squareIcon(size, { ground: c.ink, fill: white, clear: true })],
    );
  }
  const faces = await openFaces(fonts);
  for (const card of CARDS) sources.push([card.file, cardSvg(card, { tokens, faces })]);
  const rasters = new Map(sources.map(([file, source]) => [file, { source, hash: sha256(RESVG, '\n', source) }]));
  return { files, rasters, problems };
}
