const stripComments = (s) => s.replace(/\/\*[\s\S]*?\*\//g, '');

const splitRules = (source) => {
  const rules = [];
  let i = 0;

  while (i < source.length) {
    while (i < source.length && /\s/.test(source[i])) i++;
    while (source.startsWith('/*', i)) {
      const end = source.indexOf('*/', i + 2);
      if (end === -1) return rules;
      i = end + 2;
      while (i < source.length && /\s/.test(source[i])) i++;
    }
    if (i >= source.length) break;

    const preludeStart = i;
    while (i < source.length && source[i] !== '{') i++;
    if (i >= source.length) break;

    const prelude = source.slice(preludeStart, i).trim();
    i++;
    const bodyStart = i;
    let depth = 1;
    let quote = '';

    while (i < source.length && depth > 0) {
      const ch = source[i];
      const prev = source[i - 1];
      if (quote) {
        if (ch === quote && prev !== '\\') quote = '';
      } else if (source.startsWith('/*', i)) {
        const end = source.indexOf('*/', i + 2);
        if (end === -1)
          throw new Error(`unterminated CSS comment in ${prelude}`);
        i = end + 2;
        continue;
      } else if (ch === '"' || ch === "'") {
        quote = ch;
      } else if (ch === '{') {
        depth++;
      } else if (ch === '}') {
        depth--;
      }
      i++;
    }

    const body = source.slice(bodyStart, i - 1).trim();
    if (prelude) rules.push({ prelude, body });
  }

  return rules;
};

const parseDeclarations = (body) => {
  const declarations = [];
  for (const part of stripComments(body).split(';')) {
    const line = part.trim();
    if (!line) continue;
    const idx = line.indexOf(':');
    if (idx === -1) continue;
    declarations.push([line.slice(0, idx).trim(), line.slice(idx + 1).trim()]);
  }
  return declarations;
};

const rules = splitRules(css);
const rootRule = rules.find((rule) => rule.prelude === ':root');
if (!rootRule) throw new Error('aesthetic.css is missing :root tokens');

const rootDecls = new Map(parseDeclarations(rootRule.body));
const tokenOrder = [...rootDecls.keys()].filter((name) =>
  name.startsWith('--ae-'),
);
const allTokenNames = new Set(tokenOrder);

const varsIn = (s) => [
  ...new Set([...s.matchAll(/var\(\s*(--ae-[\w-]+)/g)].map((m) => m[1])),
];

const expandTokens = (tokens) => {
  const out = new Set(tokens.filter((name) => allTokenNames.has(name)));
  const queue = [...out];

  for (let i = 0; i < queue.length; i++) {
    const token = queue[i];
    const dark = `${token}-dark`;
    if (!token.endsWith('-dark') && allTokenNames.has(dark) && !out.has(dark)) {
      out.add(dark);
      queue.push(dark);
    }
    for (const ref of varsIn(rootDecls.get(token) || '')) {
      if (!out.has(ref) && allTokenNames.has(ref)) {
        out.add(ref);
        queue.push(ref);
      }
    }
  }

  return out;
};

const tokenCss = (tokens, { includeColorScheme = false } = {}) => {
  const expanded = expandTokens([...tokens]);
  const ordered = tokenOrder.filter((token) => expanded.has(token));
  const lines = ordered.map((token) => `  ${token}: ${rootDecls.get(token)};`);
  if (includeColorScheme) lines.push('  color-scheme: light dark;');

  const darkAssignments = ordered
    .filter(
      (token) => !token.endsWith('-dark') && expanded.has(`${token}-dark`),
    )
    .map((token) => `    ${token}: var(${token}-dark);`);

  const parts = [`:root {\n${lines.join('\n')}\n}`];
  if (darkAssignments.length) {
    parts.push(`@media (prefers-color-scheme: dark) {
  :root:not(.light):not([data-ae-mode='light']) {
${darkAssignments.join('\n')}
  }
}`);
  }
  parts.push(`.light,
[data-ae-mode='light'] {
  color-scheme: light;
}`);
  if (darkAssignments.length) {
    parts.push(`.dark,
[data-ae-mode='dark'] {
  color-scheme: dark;
${darkAssignments.join('\n').replace(/^    /gm, '  ')}
}`);
  }

  return { css: parts.join('\n\n'), tokens: ordered };
};

const basePrelude = (prelude) => {
  const compact = prelude.replace(/\s+/g, ' ').trim();
  return (
    compact === 'html' ||
    compact === 'body' ||
    compact === '::selection' ||
    compact === ':focus-visible' ||
    compact === 'a' ||
    compact === 'a:hover' ||
    compact.startsWith('h1,') ||
    compact.startsWith('code,')
  );
};

const selectorMatches = (prelude, markers) => {
  const stripped = stripComments(prelude);
  return stripped.split(',').some((selector) => {
    const classes = [...selector.matchAll(/\.(-?[_a-zA-Z]+[\w-]*)/g)].map(
      (match) => match[1],
    );
    const aeClasses = classes.filter((name) => name.startsWith('ae-'));
    const classMatch =
      aeClasses.length > 0 &&
      aeClasses.every((name) => markers.classes.has(name));
    const attrMatch = [...markers.attributes].some((attr) =>
      selector.includes(attr),
    );
    const elementMatch = [...markers.elements].some((element) =>
      new RegExp(`(^|[\\s>+~])${element}(?=$|[\\s.#:[>+~])`).test(selector),
    );
    return classMatch || attrMatch || elementMatch;
  });
};

const renderRule = (rule) => `${rule.prelude} {\n${rule.body}\n}`;

const filteredPrelude = (
  prelude,
  predicate,
  { splitSelectors = false } = {},
) => {
  if (!splitSelectors) return predicate(prelude) ? prelude : '';
  return prelude
    .split(',')
    .map((selector) => selector.trim())
    .filter(predicate)
    .join(',\n');
};

const filterRule = (rule, predicate, options = {}) => {
  if (!rule.prelude.startsWith('@')) {
    const prelude = filteredPrelude(rule.prelude, predicate, options);
    return prelude ? renderRule({ ...rule, prelude }) : '';
  }

  if (rule.prelude.startsWith('@keyframes')) return '';

  const inner = splitRules(rule.body)
    .map((child) => filterRule(child, predicate, options))
    .filter(Boolean)
    .join('\n\n');
  return inner ? `${rule.prelude} {\n${indent(inner)}\n}` : '';
};

const indent = (s) =>
  s
    .split('\n')
    .map((line) => (line ? `  ${line}` : line))
    .join('\n');

const selectedRules = (predicate, options = {}) =>
  rules
    .map((rule) => filterRule(rule, predicate, options))
    .filter(Boolean)
    .join('\n\n');

const keyframeRules = (ruleCss) => {
  const names = new Set(
    [...ruleCss.matchAll(/animation(?:-name)?:\s*([a-zA-Z_][\w-]*)/g)].map(
      (m) => m[1],
    ),
  );
  return rules
    .filter(
      (rule) =>
        rule.prelude.startsWith('@keyframes') &&
        names.has(rule.prelude.replace('@keyframes', '').trim()),
    )
    .map(renderRule)
    .join('\n\n');
};

const baseRuleCss = selectedRules(basePrelude);
const baseTokens = expandTokens(varsIn(baseRuleCss));
const baseTokenCss = tokenCss(baseTokens, { includeColorScheme: true });
const baseCss = [
  `/* aesthetic base v${version} — generated by scripts/build-registry.mjs. */`,
  baseTokenCss.css,
  baseRuleCss,
].join('\n\n');

const classesFrom = (s) => {
  const names = new Set();
  for (const match of s.matchAll(/class="([^"]+)"/g)) {
    for (const name of match[1].split(/\s+/)) {
      if (name.startsWith('ae-')) names.add(name);
    }
  }
  for (const match of s.matchAll(/\.([a-z0-9-]*ae-[a-z0-9-]+)/g)) {
    names.add(match[1]);
  }
  return [...names].sort();
};

const EXTRA_CLASSES = {
  buttons: ['ae-button-compact', 'ae-button-quiet', 'ae-icon'],
  dialog: ['ae-button', 'ae-button-quiet'],
  figures: ['ae-icon', 'ae-ok', 'ae-warn', 'ae-err'],
  plot: ['ae-ok', 'ae-warn', 'ae-err'],
  status: ['ae-icon'],
  toast: ['ae-icon', 'ae-ok', 'ae-warn', 'ae-err', 'ae-toast-x'],
  validation: ['ae-icon', 'ae-err'],
};

const EXTRA_RECIPES = {
  dialog: ['dialog.js'],
};

const primitiveMarkers = (primitive) => {
  const extraClasses = EXTRA_CLASSES[primitive.route] || [];
  const text = [
    primitive.classes.join(' '),
    primitive.markup,
    primitive.note || '',
  ].join('\n');

  const attributes = new Set();
  if (text.includes('data-ae-tip')) attributes.add('[data-ae-tip]');
  if (text.includes('data-ae-anticipate'))
    attributes.add('[data-ae-anticipate]');

  return {
    classes: new Set([...classesFrom(text), ...extraClasses]),
    attributes,
    elements: new Set(),
  };
};

const cssForPrimitive = (primitive) => {
  const markers = primitiveMarkers(primitive);
  const ruleCss = selectedRules(
    (prelude) => selectorMatches(prelude, markers),
    { splitSelectors: true },
  );
  const animationCss = keyframeRules(ruleCss);
  const tokens = [...expandTokens(varsIn([ruleCss, animationCss].join('\n')))]
    .filter((token) => !baseTokens.has(token))
    .sort((a, b) => tokenOrder.indexOf(a) - tokenOrder.indexOf(b));
  const primitiveTokenCss = tokenCss(tokens).css;
  const cssParts = [
    `/* aesthetic ${primitive.route} v${version} — generated by scripts/build-registry.mjs. */
@import './aesthetic.base.css';`,
  ];
  if (tokens.length) cssParts.push(primitiveTokenCss);
  cssParts.push(ruleCss);
  if (animationCss) cssParts.push(animationCss);

  return {
    css: cssParts.filter(Boolean).join('\n\n') + '\n',
    classes: [...markers.classes].sort(),
    attributes: [...markers.attributes].sort(),
    tokens,
  };
};

const itemDescription = (primitive, cssInfo, recipes) => {
  const selectors = [...cssInfo.classes, ...cssInfo.attributes].join(', ');
  const recipeText = recipes.length ? ` Recipes: ${recipes.join(', ')}.` : '';
  return `Aesthetic ${primitive.title} primitive, v${version}. Installs ${selectors || 'the base registers'} without the full stylesheet.${recipeText}`;
};

