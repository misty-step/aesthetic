const escapeHtml = (s) =>
  s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

const generatedFiles = async () => {
  const files = new Map();
  files.set(
    'site/r/registry.json',
    await json(
      {
        $schema: 'https://ui.shadcn.com/schema/registry.json',
        name: 'misty-step',
        homepage: registryOrigin,
        items: allItems.map(indexItem),
      },
      'site/r/registry.json',
    ),
  );

  for (const item of allItems) {
    files.set(
      `site/r/${item.name}.json`,
      await json(
        { $schema: 'https://ui.shadcn.com/schema/registry-item.json', ...item },
        `site/r/${item.name}.json`,
      ),
    );
  }
  files.set(
    'site/r/index.html',
    await prettier.format(registryIndexHtml(), {
      ...(await prettier.resolveConfig('site/r/index.html')),
      parser: 'html',
    }),
  );
  return files;
};

const generated = await generatedFiles();

if (process.argv.includes('--check')) {
  const failures = [];
  for (const [path, content] of generated) {
    const full = join(root, path);
    if (!existsSync(full) || read(path) !== content) failures.push(path);
  }
  const expectedJson = new Set(
    [...generated.keys()]
      .filter((path) => path.startsWith('site/r/') && path.endsWith('.json'))
      .map((path) => path.replace('site/r/', '')),
  );
  for (const name of readdirSync(outDir)) {
    if (!name.endsWith('.json') || GENERATED_JSON_KEEP.has(name)) continue;
    if (!expectedJson.has(name)) failures.push(`site/r/${name} (stale)`);
  }
  if (failures.length) {
    console.error(
      `site/r registry is out of date — run: npm run build:registry\n${failures
        .map((path) => `  - ${path}`)
        .join('\n')}`,
    );
    process.exit(1);
  }
  console.log(
    `site/r registry matches ${allItems.length} items (${primitiveItems.length} primitives, v${version}).`,
  );
} else {
  mkdirSync(outDir, { recursive: true });
  const expected = new Set(
    [...generated.keys()]
      .filter((path) => path.startsWith('site/r/') && path.endsWith('.json'))
      .map((path) => path.replace('site/r/', '')),
  );
  for (const name of readdirSync(outDir)) {
    if (!name.endsWith('.json') || GENERATED_JSON_KEEP.has(name)) continue;
    if (!expected.has(name)) unlinkSync(join(outDir, name));
  }
  for (const [path, content] of generated) write(path, content);
  console.log(
    `site/r/: registry.json + ${allItems.length} item files (${primitiveItems.length} primitives, v${version}).`,
  );
}
