/* build the registry: static JSON served from the site (site/r/) in
   the shadcn universal registry shape. The whole-file items remain for
   consumers who want the kit as one artifact; the primitive tier emits
   one copy-to-own item per catalog primitive, with only its CSS slice and
   recipe singles. Generated by CI/release; never edit site/r by hand. */
